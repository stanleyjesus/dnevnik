/** Тяжёлый день силовой роли: 3 × 4 одним весом на 83%, у изоляции 3 × 6 на 79%; вес решает запас в последнем подходе («Новая схема»,
    решение владельца 24 ноября 2026; strength.ts, DAY_H и ISO). С таблицей дней эталона тяжёлый день — 4 × 4 (AUTO, goals.ts) */
export const heavyOf = (cfg: Cfg, id: string) => isoLift(cfg, id) ? ISO : DAY_H;
/* Вес тяжёлого дня по запасу (решение владельца, 25 ноября 2026, вывод 6 аудита; разбор — docs/03, раздел 16). Решение по запасу в последнем подходе прежнее:
   0 или не закрыл — вниз, 1 — тот же вес, 2 и больше или не отмечен — вверх. Меняется, насколько вверх и вниз:
   - запас от 4 — сразу несколько шагов: около 2.5% веса на каждый повтор запаса сверх двух, как в поправке «Недогруз» у подсобки;
   - шаг больше 5% веса (бицепс со штангой: 2.5 кг на 30 кг — это 8%) — сначала повторы: 3 × 4 → 3 × 5 → 3 × 6 одним весом, потом шаг и снова 3 × 4;
     не закрыл на 3 × 5 или 3 × 6 — назад на повтор тем же весом, а не −5%.
   ACSM советует прибавлять 2–10% веса, в мелких упражнениях меньше; вес по запасу работает не хуже процентов, когда его подгоняют под запас
   (Helms и соавт., 2018; Hickmott и соавт., 2022) [И]. Точные пороги — правило дневника [Т] */
/** Тяжёлый день: с какого запаса прибавка в несколько шагов (fast), доля веса на повтор запаса сверх цели (per), шаг больше какой доли веса — сначала повторы (big),
    на сколько повторов выше обычных они растут (reps), больше какой доли веса за раз не прибавляется (max: 10%, верх совета ACSM) */
export const HEAVY = { fast: 4, per: 0.025, big: 0.05, reps: 2, max: 0.1 };
/** Следующий тяжёлый день: lw — вес прошлого раза, q — шаг, lr — его повторы, r0 — обычные повторы дня (4, у изоляции 6), verdict — по запасу, rz — запас последнего подхода */
export function heavyStep(lw: number, q: number, lr: number, r0: number, verdict: string, rz: number | null) {
  const big = lw > 0 && q / lw > HEAVY.big + 1e-9, fix = (v: number) => +v.toFixed(3);
  if (verdict === 'hold') return { w: lw, reps: lr, verdict, steps: 0 };
  if (verdict === 'down') {
    if (big && lr > r0) return { w: lw, reps: lr - 1, verdict: 'back', steps: 0 };
    return { w: fix(Math.min(lw - q, Math.round(lw * (1 - AUTO_DOWN / 100) / q) * q)), reps: r0, verdict, steps: -1 };
  }
  const k = rz != null && rz >= HEAVY.fast && q > 0 ? Math.min(Math.round((rz - AUTO_AIM) * HEAVY.per * lw / q), Math.floor(HEAVY.max * lw / q + 1e-9)) : 0;
  if (k >= 2 || (k >= 1 && big)) return { w: fix(lw + k * q), reps: r0, verdict: 'up', steps: k };
  if (big && lr < r0 + HEAVY.reps) return { w: lw, reps: lr + 1, verdict: 'reps', steps: 0 };
  return { w: fix(lw + q), reps: r0, verdict: 'up', steps: 1 };
}
/* Проверка запаса (решение владельца, 25 ноября 2026, вывод 11 аудита; docs/03, раздел 16): люди ошибаются в запасе в среднем примерно на повтор
   и чаще недооценивают, сколько могли ещё (Halperin и соавт., 2022) [И]. Если журнал старше четырёх недель, а за последние четыре недели ни один подход изоляции
   не дошёл до отказа, план предлагает поправкой: последний подход одного изолирующего упражнения — до отказа. Поправку можно снять; принятая, она пишет заметку
   к упражнению. Раз в 4–6 недель и изоляция, а не базовое, — тренерское правило [Т] */
/** Проверка запаса: сколько дней журнала до первой проверки и между проверками; заметка, которую поправка ставит упражнению */
export const RIR_CHECK = { days: 28, note: 'Проверка запаса: последний подход — до отказа' };
/* Запас 2 в многосуставных со свободным весом, где отказ опасен или ломает технику (решение владельца, 25 ноября 2026, вывод 10 аудита; docs/03, раздел 16):
   на штанге — приседания, становая, румынская тяга, тяга в наклоне, жимы; румынская и становая с гантелями. Ягодичный мост и гиперэкстензия — нет: отказ в них не опасен.
   В тренажёрах, на блоке, в изоляции и с весом тела — запас профиля, по умолчанию 1. Запас 2 почти не теряет в росте против 1 (Robinson и соавт., 2024;
   Refalo и соавт., 2023), а после подходов у самого отказа восстановление дольше (Morán-Navarro и соавт., 2017) [И]; список упражнений — тренерское правило [Т] */
export const FREE_RIR = 2;
const SAFE_HINGE = /мост|bridge|thrust|гипер|hyperext/;
/** Многосуставное со свободным весом, где запас не меньше двух: штанга, кроме моста и гиперэкстензии, и тяги от пола с гантелями */
export function freeLift(cfg: Cfg, id: string, def?: ExDef) {
  const e = def || cfg.ex[id];
  if (!appRules() || !e || e.mode === 'light' || !e.pat || e.pat === 'iso' || SAFE_HINGE.test((e.n || '').toLowerCase())) return false;
  const g = e.gear || '', gn = ((cfg.gear || {})[g] || {} as { n?: string }).n || '';
  return g === 'barbell' || /штанг/i.test(gn) || (e.pat === 'hinge' && (g === 'dumbbell' || /гантел/i.test(gn)));
}
/* Отдых между подходами дневник ставит упражнению сам (просьба владельца, 25 ноября 2026: «от человека — сколько времени он готов потратить на тренировку,
   а отдых посчитай сам для каждого упражнения»). С днями «День N» выбора отдыха на экране нет: время тренировки (time.ts, estMinutes), сборка и подсказка
   в карточке упражнения берут отдых упражнения:
   - тяжёлый день силовой роли и поддержание — 5 мин (выбор владельца тем же днём вместо 4): подходы около 83% максимума; для силы отдых от 2–3 минут
     лучше коротких пауз (Grgic и соавт., 2018) [И];
   - лёгкий и средний день и тяжёлый день изоляции в силовой роли — 3 мин;
   - многосуставные со свободным весом (freeLift: штанга, тяги от пола с гантелями) — 2 мин 30 с; остальные многосуставные — тренажёры, блоки, гантели, вес тела — 2 мин;
     в многосуставных 3 минуты дали больше роста, чем 1 минута (Schoenfeld и соавт., 2016) [И];
   - изоляция — 2 мин (выбор владельца тем же днём вместо 1 мин 30 с); по метаанализу дольше 90 секунд рост почти не прибавляет (Singer и соавт., 2024) [И].
   Точные числа — правило дневника [Т]. У пары сторон (uni) отдых между сторонами — половина, как раньше. С таблицей дней эталона — отдых профиля, как в эталоне */
/** Отдых между подходами по типу упражнения, секунд */
export const REST = { heavy: 300, light: 180, free: 150, other: 120, iso: 120 };
/** Отдых между подходами упражнения id, секунд (def — описание, когда упражнения ещё нет в справочнике профиля) */
export function restOf(cfg: Cfg, id: string, def?: ExDef) {
  const e = def || cfg.ex[id];
  if (!e) return REST.other;
  if (e.mode === 'light') return REST.light;
  if (e.mode === 'cycle' && byPct(cfg, id)) return isoLift(cfg, id) ? REST.light : REST.heavy;
  if (!e.pat || e.pat === 'iso') return REST.iso;
  return freeLift(cfg, id, e) ? REST.free : REST.other;
}
/* Разминочные подходы по типу упражнения (решение владельца, 25 ноября 2026; docs/03, раздел 20). Их одинаково считают оценка времени тренировки
   (time.ts, estMinutes) и раскладка разминки в карточке упражнения. С днями «День N»:
   - тяжёлый день силовой роли и поддержание — 4 подхода;
   - лёгкий и средний день, изоляция в силовой роли, базовое на двойной прогрессии — 2;
   - многосуставное со свободным весом (freeLift) первым на свою основную мышцу — 2;
   - любое другое упражнение первым на свою основную мышцу — 1;
   - основная мышца в этой тренировке уже работала (основной или помогающей) — 0.
   Подход разминки вместе с отдыхом и сменой веса — 1 мин 30 с. Правило тренерское [Т] */
export const WARM = { heavy: 4, light: 2, free: 2, first: 1, sec: 90 };
/** Сколько разминочных подходов у упражнения id; fresh — его основная мышца в этой тренировке ещё не работала */
export function warmSets(cfg: Cfg, id: string, fresh: boolean) {
  const e = cfg.ex[id];
  if (!e) return fresh ? WARM.first : 0;
  if (e.mode === 'light') return WARM.light;
  if (e.mode === 'cycle') return byPct(cfg, id) && !isoLift(cfg, id) ? WARM.heavy : WARM.light;
  if (!fresh) return 0;
  return freeLift(cfg, id, e) ? WARM.free : WARM.first;
}
/** Есть ли у упражнения основная мышца, которой нет среди уже работавших в этой тренировке (warm) */
export const freshFor = (m: MuscleMap | undefined, warm: Set<string>) => Object.entries(m || {}).some(([k, c]) => c >= 1 && !warm.has(k));
/** Раскладка разминки (просьба владельца, 25 ноября 2026; docs/03, раздел 17): по числу разминочных подходов — доля рабочего веса в процентах и повторы.
    [И] разминка в том же упражнении — около 40–80% рабочего веса, повторов мало, последний подход ближе к рабочему весу (Ribeiro и соавт., 2021;
    Abad и соавт., 2011: 50% × 8 и 70% × 3 от максимума); [Т] лесенка и повторы: каждый следующий подход тяжелее и короче, чтобы не устать до рабочих */
export const WARM_STEPS: Record<number, [number, number][]> = { 1: [[70, 5]], 2: [[50, 6], [80, 3]], 4: [[40, 6], [60, 4], [75, 2], [90, 1]] };
export interface WarmSet { pct: number; r: number; w: number | null }
/** Разминочные подходы перед рабочим весом w: вес вниз до шага снаряда, подходы с тем же весом или не легче рабочего не повторяются.
    Без рабочего веса или когда в вес входит тело — w: null (доля рабочего веса или «полегче») */
export function warmPlan(cfg: Cfg, id: string, n: number, w: number | null | undefined, step: number): WarmSet[] {
  const L = n <= 0 ? [] : WARM_STEPS[n] || WARM_STEPS[n >= 4 ? 4 : n >= 2 ? 2 : 1];
  if (!w || w <= 0 || withBody(cfg, id)) return L.map(([pct, r]) => ({ pct, r, w: null }));
  const out: WarmSet[] = [];
  for (const [pct, r] of L) {
    const x = step > 0 ? Math.floor(w * pct / 100 / step + 1e-9) * step : Math.floor(w * pct / 100);
    const v = Math.round(x * 1000) / 1000;
    if (v > 0 && v < w && !out.some(o => o.w === v)) out.push({ pct, r, w: v });
  }
  return out;
}
/** Отдых словами: «4 мин», «2 мин 30 с» */
export const restWords = (sec: number) => Math.floor(sec / 60) + ' мин' + (sec % 60 ? ' ' + (sec % 60) + ' с' : '');
/* метка отдыха в карточке упражнения. Стороны в паре идут по очереди: пока работает одна, отдыхает другая, — поэтому между сторонами отдых вдвое короче,
   а у каждой стороны между её подходами он тот же, что у упражнения (так же считает и оценка времени, time.ts) */
export function restTag(cfg: Cfg, id: string) {
  const r = restOf(cfg, id);
  return (cfg.ex[id] || {} as ExDef).uni ? 'отдых ' + restWords(r / 2) + ' между сторонами' : 'отдых ' + restWords(r);
}
/** Запас по методике для упражнения: у многосуставных со свободным весом не меньше двух, у остальных — запас профиля */
export const rirOf = (cfg: Cfg, id: string) => freeLift(cfg, id) ? Math.max(cfg.rir, FREE_RIR) : cfg.rir;
/** Запас словами для заметки сборки о нескольких упражнениях */
export function rirText(cfg: Cfg, ids: string[]) {
  const r = [...new Set(ids.map(id => rirOf(cfg, id)))];
  return r.length === 1 ? 'с запасом ' + r[0] : 'с запасом ' + cfg.rir + ', со свободным весом ' + Math.max(cfg.rir, FREE_RIR);
}
/* Варианты, где мышца работает растянутой (решение владельца, 25 ноября 2026, вывод 3 аудита; docs/03, раздел 16): сгибания ног сидя дали больше роста
   бицепса бедра, чем лёжа (Maeo и соавт., 2021), разгибания на трицепс из-за головы — больше, чем вниз на блоке (Maeo и соавт., 2022) [И].
   Сборка из упражнений на ту же мышцу берёт такой вариант раньше, кнопка «+» у мышцы — тоже, и в списке замены он выше. Для других мышц данных мало — там порядок прежний */
/** Насколько сборка и кнопка «+» предпочитают растянутый вариант: столько стоит новое упражнение меньше обычного */
export const LONG_K = 0.1;
export const LONG_NAME = { hams: /сидя|seated/, triceps: /из.за головы|над головой|overhead/ };
/** 1 — изоляция на бицепс бедра или трицепс в растянутом положении, иначе 0; только с днями «День N» */
export function stretchOf(e: { n?: string; m?: MuscleMap; pat?: string } | null | undefined) {
  if (!appRules() || !e || e.pat !== 'iso') return 0;
  const n = (e.n || '').toLowerCase(), m = e.m || {};
  return (m.hams || 0) >= 1 && LONG_NAME.hams.test(n) ? 1 : (m.triceps || 0) >= 1 && LONG_NAME.triceps.test(n) ? 1 : 0;
}
/* Разнообразие и прямая работа (просьба владельца, 28 ноября 2026, пункты 6, 8 и 9; docs/03, раздел 23). Только с днями «День N».
   - Упражнение вне силовой роли, которое уже стоит в другом дне недели, стоит поиску VARY_PEN, если в справочнике есть другое упражнение
     на те же основные мышцы, которого в неделе нет и которое растягивает мышцу не меньше: повтор остаётся, только когда без него объём
     недели хуже (растянутый вариант — например, сгибания ног сидя — повторяется, а не меняется на менее растянутый). Смена упражнений по дням недели даёт столько же роста и силы, сколько одно упражнение
     (Kassiano и соавт., 2024), и может развивать мышцу равномернее (Fonseca и соавт., 2014); вредит хаотичная смена каждую тренировку
     (обзор Kassiano и соавт., 2022) — здесь неделя одна и та же, каждое упражнение растёт от недели к неделе [И]. Сила — в движении цели,
     его дни не меняются.
   - Многосуставное, где основные мышцы — только руки (жим лежа узким хватом), сборка ставит, только когда у этих мышц в неделе уже есть
     изоляция или мышца в приоритете (там нужен объём, а не выбор упражнения), и эта изоляция не уходит из недели, пока оно стоит: трицепс и так получает половину подхода
     в каждом жиме, а отдельная работа на него — изоляция, первой растянутая: разгибания из-за головы дали трицепсу примерно в 1,4 раза больше роста,
     чем разгибания вниз (Maeo и соавт., 2023) [И]. В заменах такое упражнение остаётся.
   - Группа «Ягодицы» в приоритете «Массы»: в неделе есть ягодичный мост и отведение ноги в сторону. Мост растит ягодицы не больше приседа (Plotkin
     и соавт., 2023) [И], но это прямая работа на них без нагрузки на колени; отведение нагружает среднюю ягодичную, которую присед, тяги и мост почти
     не берут, — данных о её росте мало, это тренерское правило [Т]. Цена недостающего — GLUTE_PEN за каждое: она выше любой выгоды по объёму,
     поэтому мост и отведение встают первыми, а остальное поиск подбирает вокруг них. У «Ног и ягодиц» правила нет: там три мышцы, и два
     упражнения только на ягодицы при двух днях забирали у остальных до 14 подходов в неделю */
/** Мышцы рук: многосуставное, где основные только они, сборка ставит после изоляции на них */
export const ARMS = ['biceps', 'triceps'];
export function armLift(e: { pat?: string; m?: MuscleMap } | null | undefined) {
  if (!appRules() || !e || !e.pat || e.pat === 'iso') return false;
  const main = Object.keys(e.m || {}).filter(k => e.m![k] >= 1);
  return main.length > 0 && main.every(k => ARMS.includes(k));
}
/** Отведение ноги в сторону по названию: в сторону, в тренажёре на отведение ног (не назад) */
export const SIDE_NAME = /в сторон|отведени\S* ног в тренаж|abduct/;
/** Прямая работа на ягодицы, когда в приоритете «Массы» группа «Ягодицы»: мост и отведение в сторону */
export const GLUTE_WORK: { id: string; n: string; is: (e: { n?: string; pat?: string; m?: MuscleMap }) => boolean }[] = [
  { id: 'bridge', n: 'ягодичный мост', is: e => e.pat === 'hinge' && ((e.m || {}).glutes || 0) >= 1 && !(((e.m || {}).hams || 0) >= 1) },
  { id: 'side', n: 'отведение ноги в сторону', is: e => e.pat === 'iso' && ((e.m || {}).glutes || 0) >= 1 && SIDE_NAME.test(String(e.n || '').toLowerCase()) }
];
/** Цена поиску за каждую недостающую прямую работу на ягодицы: выше любой выгоды по объёму */
export const GLUTE_PEN = 1000;
/** Цена поиску за то же упражнение ещё в одном дне, когда в справочнике есть другое на те же основные мышцы */
export const VARY_PEN = 2;
/* Лёгкий и средний день слушают запас (решение владельца, 25 ноября 2026, вывод 7 аудита; docs/03, раздел 16). Вес дня — доля от расчётного максимума
   плюс сдвиг в шагах, который живёт в журнале: сдвиг прошлого раза — его вес против доли от максимума, записанного с ним (вес, поправленный руками, сдвиг снимает).
   Запас в последнем подходе 4 и больше два раза подряд при том же сдвиге — на шаг выше; 0 или подходы не закрыты — на шаг ниже; иначе сдвиг тот же.
   Не дальше двух шагов от доли и всегда легче тяжёлого дня. Около 2 в запасе — цель дня (Helms и соавт., 2018: вес по запасу) [И]; пороги 4 и 0 — правило дневника [Т] */
/** Лёгкий день: с какого запаса вес растёт (easy, два раза подряд), насколько далеко от доли максимума он уходит (far, шагов) */
export const LIGHT_RIR = { easy: 4, far: 2 };
/** Что решил запас прошлого раза в лёгком дне, словами: move — шаг вверх (1) или вниз (−1) */
export const lightWhy = (move: number) => move > 0 ? 'запас дважды подряд ' + LIGHT_RIR.easy + ' и больше: вес на шаг выше' : 'в прошлый раз запаса не было или подходы не закрыты: вес на шаг ниже';
/** Сдвиг лёгкого дня: hist — прошлые разы этого дня, от старых к новым: сдвиг в шагах (off), запас последнего подхода (rz), все подходы закрыты (closed) */
export function lightShift(hist: { off: number; rz: number | null; closed: boolean }[]) {
  const n = hist.length, last = hist[n - 1], prev = hist[n - 2];
  if (!last) return { steps: 0, move: 0 };
  const k0 = last.off, easy = (x: { rz: number | null }) => x.rz != null && x.rz >= LIGHT_RIR.easy;
  const want = !last.closed || last.rz === 0 ? -1 : prev && prev.off === k0 && easy(last) && easy(prev) ? 1 : 0;
  const steps = Math.max(-LIGHT_RIR.far, Math.min(LIGHT_RIR.far, k0 + want));
  return { steps, move: steps - k0 };
}
/** В вес входит тело: подтягивания, отжимания, брусья — по названию упражнения или его снаряда. Лёгкий день такого базового не легче
    самого лёгкого веса в журнале (легче тела не бывает); у остальных он — ровно доля от расчётного максимума, и у новой цели тоже (пункт 8, 24 ноября 2026) */
export const BODY_NAME = /подтяг|отжим|брус/;
export function withBody(cfg: Cfg, id: string) {
  const e = cfg.ex[id], g = e && e.gear ? cfg.gear[e.gear] : null;
  return !!e && (BODY_NAME.test(String(e.n || '').toLowerCase()) || (!!g && BODY_NAME.test(String(g.n || '').toLowerCase())));
}
/** Роли программы: on — что идёт по проценту; plain — базовые справочника, кроме on, идут по двойной прогрессии */
export interface Roles { on: string[]; plain: boolean }
/** Роли принятой программы: «Сила: тройка» и «Сила: <упражнение>» — по проценту только цель; «Гибрид» — цель и остальные базовые справочника,
    а с остальными «как подсобка» — только цель;
    «Масса», «Вручную» и силовой режим «все базовые», принятый до 24 ноября 2026, — справочник как есть */
export function programRoles(P: ProgramCfg | null | undefined): Roles | null {
  if (!appRules() || !P) return null;
  if (P.triad && P.triad.length) return { on: P.triad.slice(), plain: true };
  return P.focus ? { on: [P.focus], plain: !!P.strength || P.others === 'plain' } : null;   // «Гибрид» с остальными базовыми «как подсобка» — как под «Силой» (25 ноября 2026)
}
/** Справочник под роли (меняет c.ex): цель — базовое, остальные базовые — по двойной прогрессии, если так велит роль. Сохранённый режим помнит
    поле stored; шаг и округление — снова от снаряда, лёгкий день цели округляет, как она */
export function applyRoles(c: Cfg, R: Roles | null) {
  if (!R) return;
  const set = (id: string, mode: string) => {
    const e = c.ex[id], x: ExDef = Object.assign({}, e, { stored: e.stored !== undefined ? e.stored : e.mode || '' });
    if (mode) x.mode = mode; else delete x.mode;
    c.ex[id] = placed(c, x);
  };
  for (const id of Object.keys(c.ex)) {
    const e = c.ex[id];
    if (e.mode === 'light') continue;
    if (R.on.includes(id)) { if (e.mode !== 'cycle') set(id, 'cycle'); }
    else if (R.plain && e.mode === 'cycle') set(id, '');
  }
  for (const id of Object.keys(c.ex)) { const e = c.ex[id]; if (e.mode === 'light' && R.on.includes(e.of!)) c.ex[id] = placed(c, e); }
}
/** Настройка со справочником, как он сохранён: роли принятой программы сняты. Всегда копия — справочник и снаряды можно менять, не трогая c */
export function asStored(c: Cfg): Cfg {
  const out: Cfg = Object.assign({}, c, { ex: Object.assign({}, c.ex), gear: Object.assign({}, c.gear) }), back: string[] = [];
  for (const id of Object.keys(out.ex)) {
    const e = out.ex[id];
    if (e.stored === undefined) continue;
    const x = Object.assign({}, e);
    if (e.stored) x.mode = e.stored; else delete x.mode;
    delete x.stored;
    out.ex[id] = placed(out, x); back.push(id);
  }
  for (const id of Object.keys(out.ex)) { const e = out.ex[id]; if (e.mode === 'light' && back.includes(e.of!)) out.ex[id] = placed(out, e); }
  return out;
}
/** Настройка, как её читает приложение; в хранилище ничего не переписывается.
    - Роли принятой программы (см. выше). Упражнение, которое в ней идёт по двойной прогрессии вместо базового, получает число подходов базового,
      если в программе его нет: так программа, принятая до 24 ноября 2026, считается и планируется без пробелов.
    - Программа вокруг одного базового, принятая с «Растут как раньше» до 24 ноября 2026: остальные базовые в ней без отметки шли по обычной волне.
      Волны в приложении нет, а «растут» — это сила по запасу раз в неделю */
export function appCfg(c: Cfg) {
  const P = c.program;
  if (!appRules() || !P || !P.slots) return;
  const R = programRoles(P);
  applyRoles(c, R);
  if (R && R.plain) for (const sl of Object.keys(P.slots)) for (const e of P.slots[sl] || []) { const x = c.ex[e.ex]; if (x && x.stored === 'cycle' && !(+e.n! > 0)) e.n = BASE_SETS; }
  if (!P.focus || P.others !== 'grow' || P.strength) return;
  for (const sl of Object.keys(P.slots)) for (const e of P.slots[sl] || []) {
    const x = c.ex[e.ex];
    if (x && x.mode === 'cycle' && e.ex !== P.focus && !x.goal) c.ex[e.ex] = Object.assign({}, x, { goal: 'auto' });
  }
}

/* Оценка стартового веса по похожему упражнению (решение владельца, 25 ноября 2026, онбординг). В эталоне этого нет.
   Пока упражнения нет в журнале и для него ничего не названо, дневник берёт названный вес похожего упражнения той же семьи —
   разовый максимум или рабочий вес с повторами (через Эпли, как в «Известных весах») — и переносит максимум долей из таблицы.
   Только штанга и гантели: вес в тренажёре и на блоке зависит от рычагов и плиток конкретного тренажёра, по штанге его не угадать.
   Доли — ниже типичных, чтобы первая тренировка была скорее легче: двойная прогрессия сама поднимет вес. Откуда числа — docs/03, раздел 15.6:
   гантели в жиме лежа — исследование (две гантели вместе ≈ 83% штанги, Saeterbakken 2011), остальное — тренерские соотношения. */
/** Семьи упражнений встроенного справочника: максимум каждого — доля максимума первого в семье; у гантелей — на одну гантель */
export const KIN: Record<string, Record<string, number>> = {
  press: { bench: 1, close_grip_bench: 0.9, incline_bench: 0.8, db_bench: 0.4, incline_db: 0.33, ohp: 0.6, db_ohp: 0.25 },
  squat: { squat: 1, lunge: 0.2, bulgarian: 0.2 },
  hinge: { deadlift: 1, rdl: 0.7, db_rdl: 0.3 },
  row: { barbell_row: 1, db_row: 0.4 },
  curl: { barbell_curl: 1, preacher_curl: 0.85, db_curl: 0.4, hammer: 0.4 }
};
/** Семья упражнения профиля и его доля: по id или названию встроенного справочника; не в семье — null */
export function kinOf(cfg: Cfg, id: string): { fam: string; k: number } | null {
  const e = cfg.ex[id];
  if (!e || e.mode === 'light') return null;
  const s = starterOf(id, e.n);
  if (!s) return null;
  for (const [fam, ks] of Object.entries(KIN)) if (ks[s]) return { fam, k: ks[s] };
  return null;
}
/** Максимум упражнения id по названным весам похожих: named(x) — названный максимум упражнения x без оценки (null — ничего не названо).
    Оценка идёт только от упражнения с долей не меньше, чем у этого, — от тяжёлого к лёгкому: доли взяты с запасом вниз,
    и деление на долю лёгкого упражнения завысило бы вес. Из нескольких названных берётся меньшая оценка.
    { max, of } — оценка и упражнение, от которого она; null — оценить не из чего */
export function kinMax(cfg: Cfg, id: string, named: (x: string) => number | null): { max: number; of: string } | null {
  if (!appRules()) return null;
  const me = kinOf(cfg, id);
  if (!me) return null;
  let best: { max: number; of: string } | null = null;
  for (const x of Object.keys(cfg.ex)) {
    if (x === id) continue;
    const o = kinOf(cfg, x), mx = o && o.fam === me.fam ? named(x) : null;
    if (!o || !mx || o.k < me.k) continue;
    const v = +(mx / o.k * me.k).toFixed(3);
    if (!best || v < best.max) best = { max: v, of: x };
  }
  return best;
}

/* Что беречь (решение владельца, 25 ноября 2026, пункт 2 разбора «Чего не хватает сборке программы»). В эталоне этого нет.
   Атлет отмечает больные места и стоп-упражнения. Больное место ничего не убирает: упражнение, которое его нагружает, остаётся в программе,
   а рядом с ним и в списке замен стоит красная пилюля с названием места — атлет сам видит, на что заменить. Стоп-упражнение сборка
   не ставит, в заменах не предлагает, а если оно стоит в программе — меняет на похожее. Какие упражнения нагружают какое место — тренерская
   таблица по названию (docs/03, раздел 18): исследования не говорят, что при хронической боли нагрузку на больное место нужно убирать
   (Smith и соавт., 2017), поэтому решает атлет. */
