/* Сколько упражнений в тренировке с выбранным временем (решение владельца, 25 ноября 2026). Время по-прежнему задаёт длину дня, но заполняется оно
   прежде всего подходами, а не новыми упражнениями: без этого за 2 ч выходило 14–15 упражнений, три из четырёх по два подхода, — у каждого своя разминка
   и настройка, а последние делаются уже уставшим. Исследования числа упражнений не задают: считаются подходы на мышцу (лимит 11 за тренировку сходится
   с Remmert и соавт., 2025, препринт: после ~11 дробных подходов за тренировку прибавки роста не видно). Поэтому числа ниже — правило дневника [Т]:
   - day — не больше 10 упражнений в тренировке (правая и левая сторона одного упражнения — одно);
   - muscle / prio — на одну мышцу не больше двух упражнений, где она основная, у мышцы в приоритете — трёх;
   - next — второе упражнение на мышцу в тот же день встаёт, только когда в первом уже 3 подхода.
   Без выбранного времени — девять упражнений, как в эталоне, и этих правил нет. Упражнения, которые в дне уже стоят, правила не убирают — кроме
   десятого: с выбранным временем лишнее сверх десяти уходит, как и то, что не укладывается во время */
export const TIME_EX = { day: 10, muscle: 2, prio: 3, next: 3 };
/* Без выбранного времени (решение владельца, 25 ноября 2026, вывод 8 аудита; docs/03, раздел 16): в дне от шести упражнений упражнение в два подхода
   отдаёт их другому упражнению того же дня на ту же основную мышцу — одно упражнение на 3–4 подхода вместо двух по два, — когда баланс недели
   от этого не хуже, второй день ни у кого не пропадает и лимит дня соблюдён (program.ts, optimise). Для роста это почти всё равно — считаются подходы
   на мышцу, а не на упражнение (Pelland и соавт.), — а каждое упражнение — это разминка, настройка снаряда и подбор веса. Порог шесть — правило
   дневника [Т]; больше пяти подходов в одном упражнении сборка не даёт, как и поиск */
export const MANY_EX = 6, MAX_SETS = 5;
/** Есть ли в дне L место упражнению id по правилам TIME_EX для мышц: не больше двух (у приоритета трёх) упражнений, где мышца основная,
    и в тех, что уже стоят, — от трёх подходов. sets(e) — подходы упражнения с учётом шага, который сейчас проверяется; у базовых
    и лёгких дней числа подходов нет — они считаются полными */
export function roomFor<E extends { ex: string; n?: number }>(L: E[], id: string, mOf: (id: string) => MuscleMap, prio: Record<string, number>, ign: Record<string, number>, sets: (e: E) => number) {
  for (const [m, c] of Object.entries(mOf(id))) {
    if (!(c >= 1) || ign[m]) continue;
    const on = L.filter(e => e.ex !== id && (mOf(e.ex)[m] || 0) >= 1);
    if (on.length + 1 > (prio[m] ? TIME_EX.prio : TIME_EX.muscle)) return false;
    if (on.some(e => e.n != null && sets(e) < TIME_EX.next)) return false;
  }
  return true;
}

