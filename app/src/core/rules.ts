/* Карты мышц по выводам аудита методики (решение владельца, 25 ноября 2026; разбор — docs/03, раздел 16).
   - Предплечья вне расчёта по умолчанию, как икры, пресс и разгибатели (OFF_APP): отдельные сгибания кистей занимали в программе столько же подходов,
     сколько грудь. Вместо них хват засчитывается половиной подхода там, где он держит вес: в тягах (горизонтальных и вертикальных), подтягиваниях,
     становой и румынской тяге и в сгибаниях на бицепс. Сравнений роста предплечий от тяг и от сгибаний кистей нет — это тренерское правило [Т].
   - Ягодицы в приседаниях — основные (1), а не помогают: глубокий присед растил ягодицы не меньше, чем квадрицепс (Kubo и соавт., 2019),
     и не хуже ягодичного моста (Plotkin и соавт., 2023) [И]. Жим ногами и гакк-приседания — как были: по ним сравнений нет.
   Меняется только карта, которую давало прежнее правило по названию или встроенный справочник; свою карту атлета дневник не трогает,
   в хранилище ничего не переписывается */
/** Мышцы вне расчёта по умолчанию в приложении сверх эталонных (config.ts, OFF_DEFAULT) */
export const OFF_APP: Record<string, number> = { forearms: 1 };
/** Становая тяга по названию (румынская — RDL_NAME) */
export const DEADLIFT_NAME = /станов|deadlift/;
/** Сгибания на бицепс по названию: не бедра */
const CURL_NAME = /бицепс|сгибан\S* рук|curl/, NOT_CURL = /б[её]др|ног|голен|leg curl|кист|запяст|wrist/;
/** Приседания по названию: не жим ногами и не гакк */
const SQUAT_NAME = /присед|squat/, NOT_SQUAT = /гакк|hack|жим\S* ног|leg press/;
const PULL_OLD: MuscleMap = { lats: 1, upper_back: 0.5, biceps: 0.5 }, ROW_OLD: MuscleMap = { upper_back: 1, lats: 0.5, delt_rear: 0.5, biceps: 0.5 };
const SQUAT_OLD: MuscleMap = { quads: 1, glutes: 0.5 }, CURL_OLD: MuscleMap = { biceps: 1 };
/** Карта мышц, как её читает приложение, по названию, движению и карте прежнего правила. Возвращает ту же карту или новую */
export function appMap(name: string | null | undefined, pat: string | null | undefined, m: MuscleMap | undefined): MuscleMap | undefined {
  if (!m) return m;
  const s = ' ' + String(name || '').toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim() + ' ';
  let out = m;
  if (isRdl(s) && sameMap(out, RDL_OLD)) out = Object.assign({}, RDL_M);
  const hinge = pat === 'hinge' && (isRdl(s) || DEADLIFT_NAME.test(s)) && (sameMap(out, RDL_OLD) || sameMap(out, RDL_M));
  const pull = (pat === 'v_pull' && sameMap(out, PULL_OLD)) || (pat === 'h_pull' && sameMap(out, ROW_OLD));
  const curl = pat === 'iso' && sameMap(out, CURL_OLD) && CURL_NAME.test(s) && !NOT_CURL.test(s);
  if (hinge || pull || curl) out = Object.assign({}, out, { forearms: 0.5 });
  if (pat === 'knee' && sameMap(out, SQUAT_OLD) && SQUAT_NAME.test(s) && !NOT_SQUAT.test(s)) out = Object.assign({}, out, { glutes: 1 });
  return out;
}

/** Упражнение справочника, как его читает приложение. Румынская тяга с картой прежнего правила по названию читается с разгибателями,
    которые помогают: так сборка не убирает её из профиля, где разгибатели вне расчёта. Хват и присед — по выводам аудита (appMap).
    Карту, которую атлет поменял сам, дневник не трогает; в хранилище ничего не переписывается. Возвращает то же упражнение или его копию с новой картой */
export function appEx(e: ExDef): ExDef {
  if (!appRules() || !e) return e;
  const m = appMap(e.n, e.pat, e.m);
  return m === e.m ? e : Object.assign({}, e, { m });
}

/* Методика под цель (решение владельца, 24 ноября 2026; разбор — docs/03, раздел 15). С днями «День N» проценты, повторы и прибавку дневник
   считает от цели программы и типа упражнения. Волна 77–82–87 с прибавкой максимума +2% в неделю не действует: волна, записанная в профиле,
   остаётся в данных, но ничего не считает.
   - По проценту от расчётного максимума идёт только базовое в силовой роли, которую ставит сборка «Сила» или «Гибрид»: сила по запасу —
     тяжёлый день 3 × 4 одним весом с запасом 2 (≈ 83%), вес решает запас в последнем подходе, лёгкий день 3 × 8 на 75%, у «Силы: <движение>»
     ещё средний день 3 × 6 на 79% («Новая схема», решение владельца 24 ноября 2026; strength.ts); или поддержание — 3 × 4 на 83%
     от максимума, который не растёт, то есть вес прежний.
   - Всё остальное, в том числе базовое в «Массе», идёт по независимой двойной прогрессии — каждый подход ведётся отдельно: многосуставные
     и базовые 6–10 повторов, изоляция 8–12 (владелец заменил ею 10–15 в тот же день), запас по методике профиля (1 повтор). Свой диапазон упражнения
     остаётся. Ширина — от шага снаряда, как раньше: шаг веса в % / 2.5, чтобы после прибавки веса нижняя граница была по силам.
   - Когда упражнение меняет способ, расчётный максимум берётся из его последних подходов (Эпли с поправкой на запас), и план продолжается
     с весов журнала, а не с нуля. */
/** Нижняя граница и наименьшая ширина диапазона по типу упражнения: многосуставные 6–10, изоляция 8–12 */
export const TYPE = { compound: { lo: 6, w: 4 }, iso: { lo: 8, w: 4 } };
/** Поддержание базового: 3 × 4 на 83% от расчётного максимума, который не растёт (83% — как у силы по запасу, AUTO.pct) */
export const HOLD = { pct: 83, reps: 4, sets: 3 };
/** Подходов у базового на двойной прогрессии — 4, как в тяжёлом дне силы по запасу первой версии (AUTO.sets); тяжёлый день силовой роли
    с «Новой схемой» — 3 подхода (strength.ts, DAY_H) */
export const BASE_SETS = 4;
/** Роль базового по его отметке: auto — сила по запасу (и прежняя тяжёлая волна «приоритет силы»), hold — поддержание, иначе двойная прогрессия */
export function appGoal(e: ExDef | null | undefined): 'auto' | 'hold' | null {
  if (!e || e.mode !== 'cycle') return null;
  return e.goal === 'auto' || e.goal === 'strength' ? 'auto' : e.goal === 'hold' ? 'hold' : null;
}
/** Упражнение идёт по проценту от расчётного максимума: в эталоне — каждое базовое, в приложении — только базовое в силовой роли */
export const byPct = (cfg: Cfg, id: string) => { const e = cfg.ex[id]; return !!e && e.mode === 'cycle' && (!appRules() || !!appGoal(e)); };
/** Что меняется в «Заменить» и что предлагается взамен (просьба владельца, 28 ноября 2026): многосуставное и изоляция, а с днями «День N» — и базовое,
    которое не идёт по проценту. В эталоне базовое всегда шло по волне, поэтому в замены не попадало; в приложении в «Массе» базовые — на двойной
    прогрессии (решение владельца, 24 ноября 2026, пункт 8), и жим ногами — замена приседу, как гакк-приседания. Лёгкий день не меняется */
export const swappable = (cfg: Cfg, id: string) => { const e = cfg.ex[id] || {} as ExDef; return e.mode === 'light' ? false : e.mode === 'cycle' ? appRules() && !byPct(cfg, id) : true; };
/** Диапазон повторов в приложении. Свой — прошлый, если его нижняя граница не 8 (8 всем давало прежнее правило), или lo–hi упражнения в справочнике.
    Иначе по типу: базовое и многосуставное — от 6, изоляция — от 8; ширина — шаг веса в % от рабочего веса / 2.5, не уже 4 повторов и не шире 8 */
export function appRange(e: ExDef | null | undefined, last: Range | null | undefined, w: number, step: number): Range {
  if (last && last.length === 2 && last[0] !== 8) return [last[0], last[1]];
  if (e && +e.lo! > 0 && +e.hi! > +e.lo!) return [+e.lo!, +e.hi!];
  const t = e && (e.mode === 'cycle' || (e.pat && e.pat !== 'iso')) ? TYPE.compound : TYPE.iso;
  const k = Math.min(8, Math.max(t.w, w > 0 ? Math.round(step / w * 100 / 2.5) : 0));
  return [t.lo, t.lo + k];
}
/** Расчётный максимум одного подхода — Эпли от повторов плюс запас: отмеченный, у подхода по проценту — по проценту,
    иначе запас по методике профиля */
export function setMax(s: SetRec, it: Item, rir: number) {
  const q = s.q != null ? s.q : it.cyc && it.cyc.pct ? Math.max(0, estRir(it.cyc.pct, s.r!)) : rir;
  return e1(s.w!, s.r! + q);
}
/** Лучший подход записи по расчётному максимуму (setMax): при равенстве — первый */
export const maxSet = (it: Item, sets: SetRec[], rir: number) => sets.reduce((t, s) => setMax(s, it, rir) > setMax(t, it, rir) ? s : t, sets[0]);
/** Расчётный максимум по подходам одной записи — лучший подход по Эпли с поправкой на запас (setMax). null — рабочих подходов нет */
export function logMax(it: Item, rir: number) {
  let best = 0;
  for (const s of work(it)) best = Math.max(best, setMax(s, it, rir));
  return best > 0 ? best : null;
}
/* Плато в двойной прогрессии (решение владельца, 26 ноября 2026; разбор «Сила, масса и плато», docs/03, раздел 21). Тренерское правило:
   прямых исследований порога нет, а «три тренировки без рекорда» давали ложное «Плато» при медленном росте и каскад «Откат» после сброса.
   1. Остановка каскада: считаются только тренировки после последнего снижения веса в этом дне — сброс «Плато», свой сброс атлета, шаг вниз.
      Пока после него не набралось двух тренировок в каждом окне, нового сброса нет.
   2. Тренд по неделям: последние 4 недели против 4 недель до них. Плато — ни лучший подход, ни один подход этого дня не вырос больше чем на 0.5%
      и вес в диапазоне не стал больше, чем был в этом дне раньше; откат — лучший подход последних недель ниже прежнего больше чем на 5%.
   Что делать (решение владельца тем же днём, пункты 3–5 разбора; adapt.ts). При плато вес не снижается, шаги по порядку:
   3. Сначала проверка запаса — последний подход до отказа (если за 8 недель её не было): оценка запаса ошибается, особенно далеко от отказа
      (исследование). Запас проверен — +1 подход, когда основной мышце по программе меньше 12 в неделю (vol; зависимость объёма и роста —
      исследование, порог — правило дневника) и в этом дне подходов не прибавлялось; 8 недель без прибавки (swap) — замена на упражнение на те же
      мышцы, если она есть (варианты упражнений — исследование, срок — тренерское правило). −10% — только при откате и разгрузке.
   4. «Мало объёма» прибавляет подход и упражнению, которое стоит, а не только растущему.
   5. После снижения веса карточка просит отметить запас (cutAsk): по нему вес возвращается за одну-две тренировки, а не шагом за тренировку. */
export const PLATEAU = { days: 28, min: 2, grow: 0.005, fall: 0.05, drop: 0.05, vol: 12, swap: 56 };
/** Статус упражнения на «Прогрессе» с днями «День N» (решение владельца, 26 ноября 2026): тот же тренд, что у «Плато» и «Откат» плана, на дату
    последней тренировки — «застой» (flat) и «откат» (down) по plateauOf, «растёт» (up), когда тренд есть и он не плато. null — тренда не видно:
    в одном из окон меньше двух тренировок после последнего снижения веса */
export function trendStatus(ss: Session[], rir: number): 'up' | 'flat' | 'down' | null {
  if (!ss.length) return null;
  const date = ss[ss.length - 1].date, p = plateauOf(ss, date, rir);
  if (p) return p.tag === 'Откат' ? 'down' : 'flat';
  const { now, before } = windowsOf(ss, date, PLATEAU.days);
  return now.length >= PLATEAU.min && before.length >= PLATEAU.min ? 'up' : null;
}
/** Статус, который показывает «Прогресс»: с днями «День N» — по тренду (trendStatus), а где тренда не видно — как раньше, три тренировки без
    рекорда (exStats); у лёгкого дня — «лёгкий день»; с таблицей дней эталона — как раньше */
export const statusOf = (cfg: Cfg, s: { id: string, ss: Session[], status: string }) => appRules() && s.status !== 'light' ? trendStatus(s.ss, rirOf(cfg, s.id)) || s.status : s.status;
/** Пункт 5: в каком-то подходе вес ниже, чем в том же подходе прошлый раз, а запас в нём не отмечен */
export const cutAsk = (sets: SetRec[], prev: SetRec[]) => sets.some((k, i) => !k.skip && k.w != null && k.q == null && !!prev[i] && prev[i].w != null && k.w < prev[i].w! - 1e-6);
/** Плато или откат упражнения двойной прогрессии перед тренировкой date: ss — его тренировки до неё по порядку, rir — запас по методике;
    days — сколько последних дней сравнивается с 4 неделями до них (8 недель — для замены, PLATEAU.swap) */
/** Окна тренда: тренировки после последнего снижения веса в дне (rest), последние days дней (now) и 4 недели до них (before) */
function windowsOf(ss: Session[], date: string, days: number) {
  const top = (x: Session) => x.sets.reduce((m, k) => Math.max(m, k.w || 0), 0), day = (x: Session) => x.slot || '', was: Record<string, number> = {};
  let from = 0;
  ss.forEach((x, i) => { const t = top(x); if (!x.item.cyc && was[day(x)] > 0 && t < was[day(x)] * (1 - PLATEAU.drop) + 1e-6) from = i; was[day(x)] = t; });
  const D = dnum(date), age = (x: Session) => D - dnum(x.date), rest = ss.slice(from);
  return { rest, age, now: rest.filter(x => age(x) <= days), before: rest.filter(x => age(x) > days && age(x) <= days + PLATEAU.days) };
}
export function plateauOf(ss: Session[], date: string, rir: number, days = PLATEAU.days): { tag: 'Плато' | 'Откат', best: Session } | null {
  const day = (x: Session) => x.slot || '', { age, now, before } = windowsOf(ss, date, days);
  if (now.length < PLATEAU.min || before.length < PLATEAU.min) return null;
  const best = (xs: Session[]) => xs.reduce((t, x) => x.metric > t.metric ? x : t, xs[0]), b0 = best(before), b1 = best(now);
  if (b1.metric > b0.metric * (1 + PLATEAU.grow)) return null;
  /* любой подход этого дня вырос — не плато: прибавка повторов или веса в одном подходе тоже прогресс */
  const per: Record<string, number> = {}, key = (x: Session, i: number) => day(x) + ':' + i;
  for (const x of before) x.sets.forEach((k, i) => { per[key(x, i)] = Math.max(per[key(x, i)] || 0, setMax(k, x.item, rir)); });
  for (const x of now) if (x.sets.some((k, i) => per[key(x, i)] > 0 && setMax(k, x.item, rir) > per[key(x, i)] * (1 + PLATEAU.grow))) return null;
  /* новый вес в диапазоне — тоже прибавка: после шага веса повторов меньше, и по Эпли рост в одно-два процента не виден */
  const heavy: Record<string, number> = {}, inRange = (x: Session) => x.sets.filter(k => !x.item.cyc && k.r! >= (x.item.range ? x.item.range[0] : 1)).reduce((m, k) => Math.max(m, k.w || 0), 0);
  for (const x of ss) if (age(x) > days) heavy[day(x)] = Math.max(heavy[day(x)] || 0, inRange(x));
  if (now.some(x => heavy[day(x)] > 0 && inRange(x) > heavy[day(x)] + 1e-6)) return null;
  return { tag: b1.metric < b0.metric * (1 - PLATEAU.fall) ? 'Откат' : 'Плато', best: b0.metric >= b1.metric ? b0 : b1 };
}
/** Вес подхода двойной прогрессии от расчётного максимума: середина диапазона с запасом по методике, вниз до шага снаряда */
export const fromMax = (tm: number, range: Range, rir: number, step: number) => { const v = Math.floor(tm / (1 + (Math.round((range[0] + range[1]) / 2) + rir) / 30) / step + 1e-6) * step; return v > 0 ? +v.toFixed(3) : null; };
/* Порядок упражнений в дне (решение владельца, 24 ноября 2026, вопрос сборки 13; разбор — docs/03, раздел 15.3). С днями «День N» сборка
   расставляет каждый день черновика; в «Вручную» порядок атлета, сборка его не трогает:
   1. Первым — то, что важнее для цели: движение цели «Гибрида» и «Силы: …» (тяжёлый или лёгкий день), затем базовое дня, затем лёгкие дни силового
      режима (сразу после тяжёлых), затем упражнения мышц в приоритете и закреплённое упражнение «на массу».
   2. На каждой ступени многосуставные — до изоляции.
   3. Соседние упражнения — на разные основные мышцы, если можно иначе, не нарушая 1 и 2.
   Из раскладок с наименьшим числом соседей на одни мышцы берётся ближайшая к прежнему порядку: раньше остаётся то, что стояло раньше.
   Правая и левая сторона одного упражнения стоят рядом и считаются одним упражнением */
/** Ступени порядка в дне: движение цели, базовое, лёгкий день, мышцы в приоритете и упражнение «на массу», остальное; у двух последних изоляция — следующая ступень */
export const ORDER = { goal: 0, base: 1, light: 2, prio: 3, rest: 5 };
/** Порядок дня. tier — ступень упражнения (меньше — раньше), mains — его основные мышцы, side — общий ключ у правой и левой стороны
    одного упражнения (null — не сторона). Если менять нечего, возвращает тот же массив, иначе новый */
export function dayOrder<T>(L: T[], tier: (e: T) => number, mains: (e: T) => string[], side: (e: T) => string | null): T[] {
  type U = { at: number; t: number; m: string[]; items: T[] };
  const units: U[] = [], open: Record<string, U> = {};
  L.forEach((e, at) => {
    const k = side(e);
    if (k != null && open[k]) { open[k].items.push(e); delete open[k]; return; }
    const u: U = { at, t: tier(e), m: mains(e), items: [e] };
    if (k != null) open[k] = u;
    units.push(u);
  });
  units.sort((a, b) => (a.t - b.t) || (a.at - b.at));
  const n = units.length, clash = (a: number, b: number) => a >= 0 && units[a].m.some(m => units[b].m.includes(m)) ? 1 : 0;
  let seq = units.map((u, i) => i);
  if (n > 2 && n <= 16) {
    /* перебор с запоминанием: что уже стоит (маска) и что стоит последним; дальше можно ставить только упражнения самой ранней ступени из оставшихся */
    const full = (1 << n) - 1, memo = new Map<number, number>();
    const next = (mask: number) => { let i = 0; while (mask & (1 << i)) i++; const out: number[] = []; for (let j = i; j < n && units[j].t === units[i].t; j++) if (!(mask & (1 << j))) out.push(j); return out; };
    const cost = (mask: number, last: number): number => {
      if (mask === full) return 0;
      const key = mask * 17 + last + 1, got = memo.get(key);
      if (got !== undefined) return got;
      let v = Infinity;
      for (const j of next(mask)) v = Math.min(v, clash(last, j) + cost(mask | (1 << j), j));
      memo.set(key, v);
      return v;
    };
    seq = [];
    for (let mask = 0, last = -1; mask !== full;) {
      const aim = cost(mask, last), j = next(mask).find(j => clash(last, j) + cost(mask | (1 << j), j) === aim)!;
      seq.push(j); mask |= 1 << j; last = j;
    }
  }
  const out = seq.flatMap(i => units[i].items);
  return out.every((e, i) => e === L[i]) ? L : out;
}
/* Цели «Силы» и «Гибрида» (решение владельца, 24 ноября 2026, пункт 8 вопросов сборки; разбор — docs/03, раздел 15.4). С днями «День N»
   «базовое» — не отметка в справочнике, а роль в программе: тяжёлый и лёгкий дни по проценту от расчётного максимума. Её получает только то,
   что выбрано целью:
   - под «Силой» — одно упражнение из списка (strength.ts, TARGETS) или «Пауэрлифтерская тройка» (TRIAD); всё остальное, в том числе базовые
     справочника, — обычные упражнения по двойной прогрессии по типу упражнения: «Остальных базовых» под «Силой» нет;
   - под «Гибридом» — одно упражнение из того же списка; остальные базовые справочника — как их ставит переключатель «Остальные базовые».
   В «Массе» и «Вручную» справочник читается, как сохранён. Роль живёт в принятой программе (programRoles) и в условиях сборки, а не в справочнике:
   в хранилище ничего не переписывается, а asStored возвращает справочник, как он сохранён. Цели нет в справочнике — сборка добавит её из встроенного */
