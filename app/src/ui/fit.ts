/* Лимит недели от времени на тренировку (функция 41 в docs/05; решение владельца, 19 ноября 2026). В эталоне этого нет.
   Атлет называет, сколько времени готов уделять одной тренировке; дневник берёт самый большой лимит недели из своего списка,
   при котором самая длинная тренировка собранной программы укладывается в это время. Время считается той же оценкой
   и с тем же округлением до 5 минут, что стоят в заголовке каждого дня программы: сколько видно на экране, столько и сравнивается.
   «Не ограничено» — лимит выбирается вручную, как в эталоне. Здесь только правило выбора; сам список и хранение — в program.ts. */

/** Что предлагает список «Время на тренировку», минут; 0 — «не ограничено» */
export const TIMES = [60, 75, 90, 105, 120];
/** Время так, как его показывает дневник (fmtDur): округление до 5 минут, не меньше 5 */
export const shown = (min: number) => Math.max(5, Math.round(min / 5) * 5);
/** Минут на тренировку из настройки профиля как она лежит в хранилище; 0 — не ограничено */
export const timeOf = (raw: { time?: number } | null | undefined) => { const v = raw ? +raw.time! : 0; return v > 0 ? v : 0; };

/** Самый большой лимит из списка, при котором самая длинная тренировка укладывается во время `time`.
    `longest(лимит)` — минуты самой длинной тренировки программы, собранной с этим лимитом; спрашивается сверху вниз и только
    пока ответ не найден: длительность не обязана расти вместе с лимитом (сборки разные), поэтому деления пополам здесь нет.
    Не укладывается ни один — возвращается самый малый лимит и `fits: false`. */
export function fitBudget(budgets: number[], longest: (budget: number) => number, time: number) {
  const list = budgets.slice().sort((a, b) => b - a);
  let min = 0;
  for (const b of list) { min = longest(b); if (shown(min) <= time) return { budget: b, fits: true, min }; }
  return { budget: list[list.length - 1], fits: false, min };
}
